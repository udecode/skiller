import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';

const projectRoot = process.cwd();
const skillsPackagePath = path.join(
  projectRoot,
  'node_modules',
  'skills',
  'package.json',
);
const skillsDistPath = path.join(
  projectRoot,
  'node_modules',
  'skills',
  'dist',
  'cli.mjs',
);
const outputPath = path.join(
  projectRoot,
  'src',
  'generated',
  'skills-agent-catalog.ts',
);

function extractAgentsObject(cliSource) {
  const startToken = 'const agents = ';
  const endToken = '\nasync function detectInstalledAgents';
  const startIndex = cliSource.indexOf(startToken);
  const endIndex = cliSource.indexOf(endToken, startIndex);

  if (startIndex === -1 || endIndex === -1) {
    throw new Error(
      'Could not locate canonical skills agent catalog in skills/dist/cli.mjs',
    );
  }

  return cliSource
    .slice(startIndex + startToken.length, endIndex)
    .trim()
    .replace(/;$/, '');
}

function evaluateAgentsObject(objectLiteral) {
  return vm.runInNewContext(`(${objectLiteral})`, {
    join: path.posix.join,
    home: '/home/skiller',
    configHome: '/config/skiller',
    codexHome: '/home/skiller/.codex',
    claudeHome: '/home/skiller/.claude',
    existsSync: () => false,
    getOpenClawGlobalSkillsDir: () => '.openclaw/skills',
    process: {
      env: {},
      cwd: () => projectRoot,
    },
  });
}

function buildOutput(packageVersion, evaluatedAgents) {
  const catalog = Object.fromEntries(
    Object.entries(evaluatedAgents)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([id, config]) => [
        id,
        {
          id,
          displayName: config.displayName,
          skillsDir: config.skillsDir,
          showInUniversalList: config.showInUniversalList !== false,
        },
      ]),
  );

  return `/**
 * This file is generated by scripts/refresh-skills-agent-catalog.mjs.
 * Source: skills@${packageVersion}
 */

export interface SkillsAgentCatalogEntry {
  id: string;
  displayName: string;
  skillsDir: string;
  showInUniversalList: boolean;
}

export const SKILLS_PACKAGE_VERSION = '${packageVersion}';

export const SKILLS_AGENT_CATALOG = ${JSON.stringify(catalog, null, 2)} as const satisfies Record<
  string,
  SkillsAgentCatalogEntry
>;

export type SkillsAgentIdentifier = keyof typeof SKILLS_AGENT_CATALOG;
`;
}

const skillsPackage = JSON.parse(await fs.readFile(skillsPackagePath, 'utf8'));
const skillsCliSource = await fs.readFile(skillsDistPath, 'utf8');
const agentsObjectLiteral = extractAgentsObject(skillsCliSource);
const evaluatedAgents = evaluateAgentsObject(agentsObjectLiteral);
const output = buildOutput(skillsPackage.version, evaluatedAgents);

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, output);

console.log(
  `[skiller] Refreshed canonical skills catalog from skills@${skillsPackage.version}`,
);
